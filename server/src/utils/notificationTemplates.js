export const getBanglaNotification = (type, data) => {
  switch (type) {
    case "property_published":
      return {
        subject: `আপনার বিজ্ঞাপন "${data.title}" সফলভাবে প্রকাশিত হয়েছে!`,
        message: `প্রিয় ${data.userName},\n\nআপনার প্রপার্টি বিজ্ঞাপনটি সফলভাবে লাইভ করা হয়েছে। এটি আগামী ৩০ দিন পর্যন্ত সক্রিয় থাকবে। বাসা ভাড়া হয়ে গেলে আপনি চাইলে ড্যাশবোর্ড থেকে বিজ্ঞাপনটি পজ (Pause) করে রাখতে পারবেন।\n\nধন্যবাদ,\nভাড়া হবে টিম`,
      };

    case "expiry_warning":
      return {
        subject: `সতর্কবার্তা: আপনার প্রপার্টি বিজ্ঞাপনের মেয়াদ আগামীকাল শেষ হচ্ছে!`,
        message: `প্রিয় ${data.userName},\n\nআপনার "${data.title}" বিজ্ঞাপনটির মেয়াদ ২৪ ঘণ্টা পর শেষ হতে চলেছে। বিজ্ঞাপনটি সচল রাখতে এখনই ড্যাশবোর্ড থেকে রিনিউ (Renew) করুন। অন্যথায় এটি স্বয়ংক্রিয়ভাবে এক্সপায়ার হয়ে যাবে।\n\nধন্যবাদ,\nভাড়া হবে টিম`,
      };

    default:
      return {
        subject: "ভাড়া হবে নোটিফিকেশন",
        message: "আপনার অ্যাকাউন্টে নতুন একটি আপডেট এসেছে।",
      };
  }
};
